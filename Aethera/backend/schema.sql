-- ==============================================================================
-- AETHERA — UNIVERSITY EDITION DATABASE SCHEMA (PostgreSQL / Supabase Ready)
-- Full Academic Suite: Auth, Profiles, Courses, Docs, RAG Vector Search, Quizzes,
-- Flashcards, Mindmaps, Study Plans, & Community Resource Hub
-- ==============================================================================

-- Enable Vector Extension for RAG Search
CREATE EXTENSION IF NOT EXISTS vector;

-- 1. USERS TABLE
CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  display_name TEXT,
  is_active BOOLEAN DEFAULT FALSE,
  activation_code TEXT,
  activation_token TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. PROFILES TABLE
CREATE TABLE IF NOT EXISTS public.profiles (
  user_id BIGINT PRIMARY KEY REFERENCES public.users(id) ON DELETE CASCADE,
  college TEXT,
  major TEXT,
  student_id TEXT,
  program TEXT,
  avatar TEXT,
  bio TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. USAGE STATS TABLE
CREATE TABLE IF NOT EXISTS public.usage_stats (
  user_id BIGINT PRIMARY KEY REFERENCES public.users(id) ON DELETE CASCADE,
  tool_usage JSONB DEFAULT '{}'::jsonb,
  streak INT DEFAULT 0,
  last_active_date DATE,
  xp INT DEFAULT 0,
  level INT DEFAULT 0,
  badges JSONB DEFAULT '[]'::jsonb,
  weekly_data JSONB DEFAULT '{}'::jsonb
);

-- 4. SAVED NOTES & GENERATIONS
CREATE TABLE IF NOT EXISTS public.saved_notes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  content TEXT NOT NULL,
  tool_type TEXT,
  tags JSONB DEFAULT '[]'::jsonb,
  is_favorite BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. CHAT SESSIONS & MESSAGES
CREATE TABLE IF NOT EXISTS public.chat_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.chat_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id BIGINT NOT NULL REFERENCES public.chat_sessions(id) ON DELETE CASCADE,
  sender TEXT NOT NULL CHECK (sender IN ('user', 'ai', 'system')),
  message TEXT NOT NULL,
  timestamp TIMESTAMPTZ DEFAULT NOW()
);

-- 6. COURSES & ACADEMIC SUBJECTS
CREATE TABLE IF NOT EXISTS public.courses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  course_code TEXT,
  title TEXT NOT NULL,
  instructor_name TEXT,
  color_code TEXT DEFAULT '#a78bfa',
  semester TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. DOCUMENTS & EXTRACTED LECTURES
CREATE TABLE IF NOT EXISTS public.documents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id BIGINT REFERENCES public.courses(id) ON DELETE SET NULL,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  file_name TEXT NOT NULL,
  file_type TEXT NOT NULL,
  file_url TEXT,
  extracted_text TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. DOCUMENT EMBEDDINGS (VECTOR / RAG SEARCH)
CREATE TABLE IF NOT EXISTS public.document_embeddings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id BIGINT NOT NULL REFERENCES public.documents(id) ON DELETE CASCADE,
  chunk_index INT NOT NULL,
  chunk_text TEXT NOT NULL,
  embedding vector(1536), -- Compatible with OpenAI / Voyage embeddings, adjust dimension if needed
  page_number INT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 9. FLASHCARD DECKS & CARDS
CREATE TABLE IF NOT EXISTS public.flashcard_decks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  course_id BIGINT REFERENCES public.courses(id) ON DELETE SET NULL,
  title TEXT NOT NULL,
  description TEXT,
  cards_count INT DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.flashcards (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  deck_id BIGINT REFERENCES public.flashcard_decks(id) ON DELETE CASCADE,
  deck_name TEXT DEFAULT 'General',
  question TEXT NOT NULL,
  answer TEXT NOT NULL,
  ease_factor NUMERIC(4,2) DEFAULT 2.5,
  repetition_count INT DEFAULT 0,
  interval_days INT DEFAULT 1,
  next_review_due TIMESTAMPTZ DEFAULT NOW(),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 10. QUIZ RESULTS & EXAM HISTORY
CREATE TABLE IF NOT EXISTS public.quiz_results (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  course_id BIGINT REFERENCES public.courses(id) ON DELETE SET NULL,
  quiz_title TEXT NOT NULL,
  score INT NOT NULL,
  total_questions INT NOT NULL,
  answers_json JSONB,
  time_taken_seconds INT DEFAULT 0,
  taken_at TIMESTAMPTZ DEFAULT NOW()
);

-- 11. MIND MAPS STORAGE
CREATE TABLE IF NOT EXISTS public.mind_maps (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  course_id BIGINT REFERENCES public.courses(id) ON DELETE SET NULL,
  title TEXT NOT NULL,
  tree_data_json JSONB NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 12. AI STUDY PLANS
CREATE TABLE IF NOT EXISTS public.study_plans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  course_id BIGINT REFERENCES public.courses(id) ON DELETE SET NULL,
  target_exam_date DATE,
  daily_target_hours NUMERIC(4,1) DEFAULT 2.0,
  plan_details_json JSONB NOT NULL,
  status TEXT DEFAULT 'active',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 13. CONCEPT MASTERY MATRIX
CREATE TABLE IF NOT EXISTS public.concept_mastery (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  subject TEXT NOT NULL,
  concept_name TEXT NOT NULL,
  mastery_score NUMERIC(4,2) DEFAULT 0.0,
  total_attempts INT DEFAULT 0,
  correct_attempts INT DEFAULT 0,
  ai_recommendation TEXT,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 14. SHARED RESOURCES (COMMUNITY HUB)
CREATE TABLE IF NOT EXISTS public.shared_resources (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  author_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  category TEXT DEFAULT 'general',
  resource_type TEXT NOT NULL, -- e.g. summary, flashcards, mindmap, exam
  content_json JSONB NOT NULL,
  likes_count INT DEFAULT 0,
  downloads_count INT DEFAULT 0,
  is_public BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 15. RESOURCE REVIEWS & RATINGS
CREATE TABLE IF NOT EXISTS public.resource_reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resource_id BIGINT NOT NULL REFERENCES public.shared_resources(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  rating INT CHECK (rating >= 1 AND rating <= 5),
  comment TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 16. SUBSCRIPTIONS & SECURITY AUDIT LOGS
CREATE TABLE IF NOT EXISTS public.subscriptions (
  user_id BIGINT PRIMARY KEY REFERENCES public.users(id) ON DELETE CASCADE,
  plan_type TEXT DEFAULT 'free',
  status TEXT DEFAULT 'active',
  stripe_customer_id TEXT,
  current_period_end TIMESTAMPTZ,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  action TEXT NOT NULL,
  ip_address TEXT,
  user_agent TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 17. INSTITUTIONS & CAMPUS ENTERPRISE
CREATE TABLE IF NOT EXISTS public.institutions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  domain TEXT UNIQUE,
  country TEXT DEFAULT 'Egypt',
  tier TEXT DEFAULT 'campus_enterprise',
  seats_total INT DEFAULT 5000,
  seats_used INT DEFAULT 0,
  license_key TEXT UNIQUE NOT NULL,
  logo_url TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 18. INSTITUTION MEMBERS
CREATE TABLE IF NOT EXISTS public.institution_members (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institution_id BIGINT NOT NULL REFERENCES public.institutions(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  role TEXT NOT NULL DEFAULT 'student',
  department TEXT DEFAULT 'Computer Science',
  status TEXT DEFAULT 'active',
  joined_at TIMESTAMPTZ DEFAULT NOW()
);

-- 19. ENTERPRISE LICENSES
CREATE TABLE IF NOT EXISTS public.enterprise_licenses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institution_id BIGINT NOT NULL REFERENCES public.institutions(id) ON DELETE CASCADE,
  license_key TEXT UNIQUE NOT NULL,
  plan_name TEXT DEFAULT 'Campus Unlimited AI',
  max_seats INT DEFAULT 10000,
  issued_date DATE,
  expires_at DATE,
  is_active BOOLEAN DEFAULT TRUE,
  contact_email TEXT
);

-- 20. INSTRUCTOR CLASSES & COHORTS
CREATE TABLE IF NOT EXISTS public.instructor_classes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institution_id BIGINT REFERENCES public.institutions(id) ON DELETE CASCADE,
  instructor_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  class_name TEXT NOT NULL,
  course_code TEXT NOT NULL,
  department TEXT DEFAULT 'Engineering',
  semester TEXT DEFAULT 'Fall 2026',
  syllabus_text TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 21. CLASS ROSTER
CREATE TABLE IF NOT EXISTS public.class_roster (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_id BIGINT NOT NULL REFERENCES public.instructor_classes(id) ON DELETE CASCADE,
  student_id BIGINT,
  student_name TEXT NOT NULL,
  student_email TEXT NOT NULL,
  enrolled_at TIMESTAMPTZ DEFAULT NOW()
);

-- 22. CLASS ASSIGNMENTS
CREATE TABLE IF NOT EXISTS public.class_assignments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_id BIGINT NOT NULL REFERENCES public.instructor_classes(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  prompt TEXT NOT NULL,
  rubric_json JSONB DEFAULT '{}'::jsonb,
  max_score INT DEFAULT 100,
  due_date DATE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 23. CLASS SUBMISSIONS & AI GRADES
CREATE TABLE IF NOT EXISTS public.class_submissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignment_id BIGINT NOT NULL REFERENCES public.class_assignments(id) ON DELETE CASCADE,
  student_id BIGINT,
  student_name TEXT NOT NULL,
  submission_text TEXT NOT NULL,
  score INT DEFAULT 0,
  letter_grade TEXT DEFAULT 'Pending',
  ai_feedback_json JSONB DEFAULT '{}'::jsonb,
  plagiarism_score NUMERIC(5,2) DEFAULT 0.0,
  ai_likelihood NUMERIC(5,2) DEFAULT 0.0,
  status TEXT DEFAULT 'graded',
  graded_at TIMESTAMPTZ DEFAULT NOW(),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 24. LMS EXPORT LOGS
CREATE TABLE IF NOT EXISTS public.lms_exports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  tool_name TEXT NOT NULL,
  lms_type TEXT NOT NULL,
  export_title TEXT NOT NULL,
  payload_json JSONB,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==============================================================================
-- INDEXES FOR MAXIMUM QUERY PERFORMANCE
-- ==============================================================================
CREATE INDEX IF NOT EXISTS idx_saved_notes_user ON public.saved_notes(user_id);
CREATE INDEX IF NOT EXISTS idx_chat_messages_session ON public.chat_messages(session_id);
CREATE INDEX IF NOT EXISTS idx_courses_user ON public.courses(user_id);
CREATE INDEX IF NOT EXISTS idx_documents_course ON public.documents(course_id);
CREATE INDEX IF NOT EXISTS idx_flashcards_user_deck ON public.flashcards(user_id, deck_id);
CREATE INDEX IF NOT EXISTS idx_quiz_results_user ON public.quiz_results(user_id);
CREATE INDEX IF NOT EXISTS idx_mind_maps_user ON public.mind_maps(user_id);
CREATE INDEX IF NOT EXISTS idx_study_plans_user ON public.study_plans(user_id);
CREATE INDEX IF NOT EXISTS idx_shared_resources_public ON public.shared_resources(is_public, category);
CREATE INDEX IF NOT EXISTS idx_institution_members ON public.institution_members(institution_id, user_id);
CREATE INDEX IF NOT EXISTS idx_class_assignments ON public.class_assignments(class_id);
CREATE INDEX IF NOT EXISTS idx_class_submissions ON public.class_submissions(assignment_id);

-- Vector Similarity Search Index (HNSW for fast cosine distance matching)
CREATE INDEX IF NOT EXISTS idx_embeddings_vector ON public.document_embeddings USING hnsw (embedding vector_cosine_ops);

